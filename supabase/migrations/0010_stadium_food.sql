-- AI 직관 플래너 "구장 내 맛집" 실데이터. schema_ai_planner.sql(stadiums 10개 전부) 다음에 실행한다.
-- "구장 내"는 이 표(사람이 직접 확인한 목록)로, "구장 주변"은 카카오 로컬 API(Edge Function
-- `stadium-food`)로 그때그때 가져온다 — 거리·주소만으로는 구장 내/외가 깨끗하게 안 갈려서
-- (같은 주소인데 거리값이 들쑥날쑥) 안/밖 구분이 필요한 "내"쪽만 사람이 확인해서 테이블로 둔다.
--
-- 원본: 카카오맵 기준 야구장 입점 매장 236건 중, "야구장 내"로 확인되고
-- "오늘야구에 있음"=Y 인 190건만 추렸다.
-- 도보 n분·평점·가격 정보는 원본에 없어서 빼고, 대신 구장 내 위치(location)로 추천 이유를 만든다.

create table public.stadium_food (
  id uuid primary key default gen_random_uuid(),
  stadium_code text not null references public.stadiums (code),
  name text not null,                 -- 매장명 (카카오맵 등록명)
  category text not null check (category in ('치킨','피자·버거','카페·디저트','분식·간식','한식·고기·주류','양식·아시안')),
  location text,                       -- 구장 내 위치, 예: "3루 3층"
  phone text,
  address text
);

alter table public.stadium_food enable row level security;
create policy "stadium_food_select_authenticated" on public.stadium_food
  for select to authenticated using (true);
revoke insert, update, delete on public.stadium_food from anon, authenticated;

